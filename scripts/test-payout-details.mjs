import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { validatePayoutDetails as validate } from '../apps/web/lib/payout-details.ts';
const require = createRequire(import.meta.url);
const { PGlite } = require('../.agent-build/test-runtime/node_modules/@electric-sql/pglite');
assert.deepEqual(validate({upi_id:' test@upi '}), {upi_id:'test@upi'});
for (const input of [null, {upi_id:42}, {upi_id:'invalid'}, {upi_id:'test@upi',account_number:'123456'}, {upi_id:'test@upi',account_holder_name:'Test',account_number:'bad',ifsc_code:'SBIN0001234'}]) assert.equal(typeof validate(input), 'string');
const complete = validate({upi_id:'test@upi',account_holder_name:'Test',account_number:'123 456',ifsc_code:'sbin0001234'});
assert.equal(complete.account_number,'123456');
assert.equal(complete.ifsc_code,'SBIN0001234');
const db = new PGlite();
await db.exec(`create table public.vendor_bank_details(shop_id int primary key, account_holder_name text not null, account_number text not null, ifsc_code text not null, upi_id text); insert into vendor_bank_details values(1,'Existing','123456','SBIN0001234','old@upi');`);
await db.exec(fs.readFileSync('supabase/migrations/20260915084301_optional_bank_details.sql','utf8'));
await db.exec(`insert into vendor_bank_details(shop_id,upi_id) values(2,'test@upi');`);
assert.equal((await db.query('select account_number from vendor_bank_details where shop_id=2')).rows[0].account_number,null);
await assert.rejects(db.exec(`insert into vendor_bank_details(shop_id,upi_id,account_number) values(3,'test@upi','123456');`));
await db.exec(`insert into vendor_bank_details(shop_id,upi_id) values(1,'new@upi') on conflict(shop_id) do update set upi_id=excluded.upi_id;`);
assert.equal((await db.query('select account_number from vendor_bank_details where shop_id=1')).rows[0].account_number,'123456');
await db.exec(`update vendor_bank_details set account_holder_name='Later',account_number='654321',ifsc_code='SBIN0001234' where shop_id=2;`);
assert.equal((await db.query('select upi_id from vendor_bank_details where shop_id=2')).rows[0].upi_id,'test@upi');
await db.close();
console.log('Payout validation and database regression checks passed.');
